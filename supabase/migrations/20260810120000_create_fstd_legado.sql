create table if not exists public.fstd_legado (
  legado_id bigint generated by default as identity primary key,
  codigo_loja text not null, numero_nfd text not null, id text not null, numero_controle text, data_preenchimento timestamptz, responsavel_fstd text, motivo text, qtd_total_galinha bigint, qtd_retorno_galinha bigint, qtd_total_codorna bigint, qtd_retorno_codorna bigint, origem text not null,
  created_at timestamptz not null default now()
);
create index if not exists fstd_legado_id_idx on public.fstd_legado (id);
create index if not exists fstd_legado_lookup_idx on public.fstd_legado (codigo_loja, numero_nfd);
alter table public.fstd_legado enable row level security;
revoke all on table public.fstd_legado from anon;
grant select on table public.fstd_legado to authenticated;
drop policy if exists fstd_legado_select_authorized on public.fstd_legado;
create policy fstd_legado_select_authorized on public.fstd_legado for select to authenticated using ((select app_private.is_current_user_gerencial_ativo()) or exists (select 1 from public.usuarios u where u.auth_user_id=(select auth.uid()) and u.ativo is true));

